/// Modes d'interaction avec le chiot Pi dans l'écran de soin et de jeu.
enum CareInteractionMode {
  play, // Jouer à la balle
  feed, // Nourrir avec assiette et croquettes
  clean, // Laver Pi dans la douche pour chien
  walk, // Guider librement
  sleep, // Dodo dans la chambre étoilée avec panier douillet
}
